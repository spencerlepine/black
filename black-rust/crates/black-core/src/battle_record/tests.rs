struct Hooks;
impl EntryHooks for Hooks {
    fn init_unk3(&self, e: &mut BattleEntry) {
        e.unk_00 = 0xAAAA0003;
    }
    fn init_end(&self, e: &mut BattleEntry) {
        e.unk_00 = 0xBBBB0004;
    }
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn en(v: &[u32]) -> Vec<BattleEntry> {
    v.iter().map(|&unk_00| BattleEntry { unk_00 }).collect()
}

