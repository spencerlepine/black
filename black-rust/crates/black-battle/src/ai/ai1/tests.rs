/// Bytes per argument slot of the emulator layout; the memory after a buffer up to the next slot is mapped and zero
/// (a fresh image per function), so a buffer is mapped padded with zeros to the full slot (as in the server3 tests).
const SLOT: usize = 0x1_0000;

/// The case's `arg buf`s at their addresses `vals[i]`, plus the global AI table word (the spec's `global 0218a7c0`, or
/// a zero word, as the emulator's fresh image has it, when the block declares none). Returns the buffer sizes.
fn take_mem(c: &mut Case) -> (Mem, Vec<usize>) {
    let mut mem = Mem::new();
    let sizes: Vec<usize> = c.bufs.iter().map(Vec::len).collect();
    for (i, b) in c.bufs.iter_mut().enumerate() {
        if !b.is_empty() {
            let mut v = std::mem::take(b);
            v.resize(SLOT, 0);
            mem.map(c.vals[i], v);
        }
    }
    let g = match c.globals.first_mut() {
        Some(g) => std::mem::take(g),
        None => vec![0; 4],
    };
    mem.map(super::AI_TABLE_PTR, g);
    (mem, sizes)
}

fn give_mem(c: &mut Case, mut mem: Mem, sizes: &[usize]) {
    for (i, &n) in sizes.iter().enumerate() {
        if n != 0 {
            let mut b = mem.unmap(c.vals[i]);
            b.truncate(n);
            c.bufs[i] = b;
        }
    }
    let g = mem.unmap(super::AI_TABLE_PTR);
    if let Some(slot) = c.globals.first_mut() {
        *slot = g;
    }
}

