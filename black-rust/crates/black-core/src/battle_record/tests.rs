/// Fixed address of `region` k of a spec function (black-fndiff `REGION_BASE`).
const REGION_BASE: u32 = 0x02F1_0000;

/// The heap routines routed to the spec's stubs.
struct StubHeap<'a>(&'a mut StubEnv);

impl RecordHeap for StubHeap<'_> {
    fn heap_alloc(&mut self, heap_id: u32, size: u32, flag: u32, file: u32, line: u32) -> u32 {
        self.0.call(
            0x0203_0734,
            &mut [
                Arg::V(heap_id),
                Arg::V(size),
                Arg::V(flag),
                Arg::V(file),
                Arg::V(line),
            ],
        )
    }
    fn heap_free(&mut self, block: u32) {
        self.0.call(0x0203_07B0, &mut [Arg::V(block)]);
    }
}

/// `FUN_overlay_d_93__021d8470` / `021d845c` routed to the spec's `out:4` stubs.
struct StubEntries<'a>(RefCell<&'a mut StubEnv>);

impl StubEntries<'_> {
    fn init(&self, addr: u32, e: &mut BattleEntry) {
        let mut b = e.to_bytes();
        self.0.borrow_mut().call(addr, &mut [Arg::Out(&mut b)]);
        *e = BattleEntry::from_bytes(&b);
    }
}

impl EntryHooks for StubEntries<'_> {
    fn init_unk3(&self, e: &mut BattleEntry) {
        self.init(0x021D_845C, e);
    }
    fn init_end(&self, e: &mut BattleEntry) {
        self.init(0x021D_8470, e);
    }
}

/// The record data the reader in `bufs[0]` points at (the spec's `region data`).
fn reader_data(c: &Case) -> Vec<u8> {
    assert_eq!(rd32(&c.bufs[0], 0), REGION_BASE, "reader data is region 0");
    c.region("data").to_vec()
}

fn call(addr: u32, c: &mut Case) -> u64 {
    match addr {
        0x021E_E5E4 => record_new(&mut StubHeap(&mut c.env), c.vals[0]) as u64,
        0x021E_E600 => {
            record_free(&mut StubHeap(&mut c.env), c.vals[0]);
            0
        }
        0x021E_E63C => {
            let mut size = 0;
            let r = record_get_data(&c.bufs[0], &mut size);
            wr32(&mut c.bufs[1], 0, size);
            r as u64
        }
        0x021E_E644 => {
            let (p, n) = (c.vals[1], c.vals[2]);
            reader_init(&mut c.bufs[0], p, n);
            0
        }
        0x021E_E674 => {
            reader_reset(&mut c.bufs[0]);
            0
        }
        0x021E_E6B8 => {
            let data = reader_data(c);
            let client = c.vals[1];
            let (mut n, mut f) = (c.bufs[2][0], c.bufs[3][0]);
            let mut reader = std::mem::take(&mut c.bufs[0]);
            let r = reader_read_next(
                &mut reader,
                &data,
                client,
                &mut n,
                &mut f,
                &StubEntries(RefCell::new(&mut c.env)),
            );
            c.bufs[0] = reader;
            c.bufs[2][0] = n;
            c.bufs[3][0] = f;
            r as u64
        }
        0x021E_E830 => {
            let data = reader_data(c);
            reader_count_flagged_tags(&c.bufs[0], &data) as u64
        }
        0x021E_E894 => reader_is_at_end(&c.bufs[0], c.vals[1]) as u64,
        0x021E_E8B4 => {
            let flag = c.vals[1];
            builder_init(&mut c.bufs[0], flag);
            0
        }
        _ => unreachable!("{addr:#010x} is PORTED but not wired into the test"),
    }
}

