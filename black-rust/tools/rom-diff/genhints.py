"""Generate crates/black-battle/src/handlers/hints.rs (the Rust mirror of HINTS in handlers.py).

Usage: python -I genhints.py [--check]   (--check: exit 1 if the file is out of date, no write)

Values (including the ME / NXT / REL+k encodings and the stub-derived move/item/seed constants)
are taken from the Python table verbatim, so the two sides cannot drift.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import handlers as H  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "../../crates/black-battle/src/handlers/hints.rs")


def vals(v):
    t = v if isinstance(v, tuple) else (v,)
    return "&[" + ", ".join("0x%X" % x for x in t) + "]"


def render():
    out = [
        "//! GENERATED by tools/rom-diff/genhints.py from `HINTS` in tools/rom-diff/handlers.py; do not",
        "//! edit by hand (check-handlers.sh regenerates it). Z18b harness hints for ability and item",
        "//! handlers; applied by `testkit::apply_hint`.",
        "",
        "/// One handler's hints; see the comment above `HINTS` in handlers.py for the semantics.",
        "pub struct Hint {",
        "    pub addr: u32,",
        "    /// (label, value alternatives by slot)",
        "    pub vars: &'static [(u16, &'static [u32])],",
        "    /// (who: 0 owner / 1 next / 2 all, offset, width, value alternatives)",
        "    pub mons: &'static [(u8, usize, usize, &'static [u32])],",
        "    /// (work word, value alternatives)",
        "    pub work: &'static [(usize, &'static [u32])],",
        "    /// Host work seed alternatives (empty = unchanged).",
        "    pub wseed: &'static [u32],",
        "}",
        "",
        "pub const ME: u32 = 0x%X;" % H.ME,
        "pub const NXT: u32 = 0x%X;" % H.NXT,
        "pub const REL: u32 = 0x%X;" % H.REL,
        "",
        "pub const HINT_TABLE: &[Hint] = &[",
    ]
    for addr in sorted(H.HINTS):
        h = H.HINTS[addr]
        out.append("    Hint {")
        out.append("        addr: 0x%08X," % addr)
        out.append("        vars: &[%s]," % ", ".join("(0x%X, %s)" % (lab, vals(v)) for lab, v in h.get("vars", [])))
        out.append("        mons: &[%s]," % ", ".join(
            "(%d, 0x%X, %d, %s)" % (w, off, width, vals(v)) for w, off, width, v in h.get("mons", [])))
        out.append("        work: &[%s]," % ", ".join("(%d, %s)" % (k, vals(v)) for k, v in h.get("work", [])))
        out.append("        wseed: %s," % (vals(h["wseed"]) if "wseed" in h else "&[]"))
        out.append("    },")
    out.append("];")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        sys.exit(0 if cur == text else 1)
    with open(OUT, "w") as f:
        f.write(text)
