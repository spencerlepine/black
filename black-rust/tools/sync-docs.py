"""Regenerate crates/*/SYMBOLS.md and tick checklists/*.md from `/// C:` doc comments.

Every ported item carries a doc comment naming its original symbol(s), e.g.
    /// C: `FUN_overlay_d_93__021d5b10` / `021d7b2c`: ...
    /// C: unlabeled routine at `0x021D778C`: ...
Short forms after a full name inherit its prefix. Run after each batch:
    python3 tools/sync-docs.py
Symbols listed in UNIT_TESTED are ticked `~` (ported, not emulator-verified).
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")

UNIT_TESTED = {
    "FUN_overlay_d_93__021d7840": "unit-tested only (heap alloc via trait)",
    "FUN_overlay_d_93__021d787c": "unit-tested only (state setter)",
    "FUN_overlay_d_93__021d7894": "unit-tested only (heap free via trait)",
    "FUN_overlay_d_93__021d804c": "unit-tested only (state setter)",
}

SYM_RE = re.compile(r"`((?:FUN|LAB|thunk)_[A-Za-z0-9_]+|0x[0-9A-Fa-f]{8}|[0-9a-f]{4,8}|[A-Z][A-Za-z0-9]+_[A-Za-z0-9_]+|[A-Z][a-z]+[A-Z][A-Za-z0-9]+)`")


def expand(tokens):
    out = []
    prefix = None
    for t in tokens:
        if t.startswith(("FUN_", "LAB_", "thunk_")):
            out.append(t)
            m = re.match(r"(.*?)([0-9a-fA-F]{8})$", t)
            prefix = m.group(1) if m else None
        elif t.startswith("0x"):
            out.append("ADDR_" + t[2:].upper())
        elif re.fullmatch(r"[0-9a-f]{4,8}", t):
            if prefix:
                base = out[-1][len(prefix):] if out else ""
                full = prefix + base[: 8 - len(t)] + t
                out.append(full)
        else:
            out.append(t)
    return out


def scan_crate(crate):
    rows = []
    src = os.path.join(ROOT, "crates", crate, "src")
    for dirpath, dirnames, files in os.walk(src):
        dirnames.sort()  # walk order is filesystem-dependent; keep SYMBOLS.md identical on every host
        for fn in sorted(files):
            if not fn.endswith(".rs") or fn == "tests.rs":
                continue
            path = os.path.join(dirpath, fn)
            mod = os.path.relpath(path, src)[:-3].replace(os.sep, "::")
            mod = mod.replace("::mod", "").replace("lib", "")
            lines = open(path).read().splitlines()
            impl = None
            for i, line in enumerate(lines):
                m = re.match(r"\s*impl(?:<[^>]*>)?\s+(?:[A-Za-z0-9_:]+\s+for\s+)?([A-Za-z0-9_]+)", line)
                if m and line.rstrip().endswith("{") and not line.startswith("    "):
                    impl = m.group(1)
                if not line.startswith(("impl", "    ", "}")):
                    if not line.startswith("impl"):
                        impl = None if line.startswith(("pub fn", "fn", "pub struct", "pub const")) else impl
                m = re.match(r"\s*/// C: (.*)", line)
                if not m:
                    continue
                head = m.group(1).split(":")[0] if "`:" in m.group(1) else m.group(1)
                syms = expand(SYM_RE.findall(head))
                if not syms:
                    continue
                item = None
                for j in range(i + 1, min(i + 40, len(lines))):
                    mm = re.match(r"\s*(?:pub(?:\(crate\))? )?(?:fn|struct|const|type|trait|mod) ([A-Za-z0-9_]+)", lines[j])
                    if mm:
                        indented = lines[j].startswith("    ")
                        item = (impl + "::" if indented and impl else "") + mm.group(1)
                        break
                if item:
                    rows.append((syms, f"{crate.replace('-', '_')}::{mod + '::' if mod else ''}{item}"))
    return rows


def main():
    crates = sorted(os.listdir(os.path.join(ROOT, "crates")))
    found = {}
    for crate in crates:
        rows = scan_crate(crate)
        if not rows:
            continue
        with open(os.path.join(ROOT, "crates", crate, "SYMBOLS.md"), "w") as f:
            f.write(f"# {crate} symbol map\n\nGenerated by `tools/sync-docs.py` from `/// C:` doc comments. Do not edit.\n\n")
            f.write("| original symbol | Rust item |\n|---|---|\n")
            for syms, item in rows:
                f.write(f"| {' / '.join('`' + s + '`' for s in syms)} | `{item}` |\n")
                for s in syms:
                    found[s] = item
    # Checklists: map labelled names and unlabeled addresses.
    for fn in sorted(os.listdir(os.path.join(ROOT, "checklists"))):
        path = os.path.join(ROOT, "checklists", fn)
        out = []
        for line in open(path):
            m = re.match(r"- \[(.)\] `([^`]+)`(.*)", line)
            if m and m.group(1) in " x~":
                sym = m.group(2)
                if sym in found:
                    mark = "~" if sym in UNIT_TESTED else "x"
                    note = f" — {UNIT_TESTED[sym]}" if sym in UNIT_TESTED else f" → `{found[sym]}`"
                    line = f"- [{mark}] `{sym}`{note}\n"
            out.append(line)
        # Unlabeled routines are appended once.
        extra = sorted(s for s in found if s.startswith("ADDR_"))
        open(path, "w").write("".join(out))
    total = sum(1 for _ in found)
    print(f"{total} symbols mapped")


if __name__ == "__main__":
    main()
