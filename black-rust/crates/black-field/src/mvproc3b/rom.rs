/// The ROM word at `addr` (word aligned, inside [`ROM_WORDS`]); panics elsewhere (the original reads whatever is there:
/// UNVERIFIED).
pub fn rom32(addr: u32) -> u32 {
    let i = addr.wrapping_sub(ROM_BASE);
    assert!(
        i.is_multiple_of(4) && (i / 4) < ROM_WORDS.len() as u32,
        "UNVERIFIED: ROM read at {addr:#010x} outside 0x021D4D04..0x021D548C"
    );
    ROM_WORDS[(i / 4) as usize]
}

/// The ROM halfword at `addr` (inside [`ROM_WORDS`]).
pub fn rom16(addr: u32) -> u32 {
    (rom32(addr & !3) >> (8 * (addr & 2))) & 0xFFFF
}
