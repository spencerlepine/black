"""Gate check (V-0021): every address in any `pub const PORTED: &[u32]` of a crate has a row in that crate's
SYMBOLS.md (regenerated by tools/sync-docs.py from the `/// C:` comments). A ported function whose `/// C:` head
the parser cannot read (or that has none) is missing from the symbol map; this makes that a gate failure.

A row matches when one of its symbols ends in the address (`FUN_overlay_d_93__021b9244`, `FUN_0201BA68`,
`ADDR_02188C54`, `sub_021bb960`, ...). A function documented only by its decomp name (no address in the symbol,
e.g. `BattleParty_SwapSlots`) is matched through NAMED below: add `addr: "name"` there when that happens.
Run: python3 -I tools/check-symbols.py   (exit 1 and a list on stderr when something is missing)
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

# ported address -> decomp name used by its `/// C:` head instead of an address-bearing symbol
NAMED = {}

PORTED_RE = re.compile(r"pub const PORTED: &\[u32\] = &\[(.*?)\];", re.S)
HEX_RE = re.compile(r"0x([0-9A-Fa-f_]+)")


def main():
    missing = []
    total = 0
    crates = sorted(os.listdir(os.path.join(ROOT, "crates")))
    for crate in crates:
        src = os.path.join(ROOT, "crates", crate, "src")
        ported = []
        for dirpath, dirnames, files in os.walk(src):
            dirnames.sort()
            for fn in sorted(files):
                if not fn.endswith(".rs"):
                    continue
                path = os.path.join(dirpath, fn)
                text = open(path).read()
                for m in PORTED_RE.finditer(text):
                    body = re.sub(r"//[^\n]*", "", m.group(1))
                    for h in HEX_RE.findall(body):
                        ported.append((int(h.replace("_", ""), 16), os.path.relpath(path, ROOT)))
        if not ported:
            continue
        sym_path = os.path.join(ROOT, "crates", crate, "SYMBOLS.md")
        have = set()
        names = set()
        if os.path.exists(sym_path):
            for line in open(sym_path):
                if not line.startswith("| `"):
                    continue
                first = line.split(" | ")[0]
                for s in re.findall(r"`([^`]+)`", first):
                    names.add(s)
                    m = re.search(r"([0-9A-Fa-f]{8})$", s)
                    if m:
                        have.add(int(m.group(1), 16))
        for addr, path in sorted(set(ported)):
            total += 1
            if addr in have or NAMED.get(addr) in names:
                continue
            missing.append((crate, addr, path))
    for crate, addr, path in missing:
        print(f"check-symbols: {crate}: PORTED 0x{addr:08X} ({path}) has no SYMBOLS.md row "
              f"(its `/// C:` head names no symbol sync-docs.py can read)", file=sys.stderr)
    print(f"check-symbols: {total - len(missing)}/{total} PORTED addresses have a SYMBOLS.md row")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
